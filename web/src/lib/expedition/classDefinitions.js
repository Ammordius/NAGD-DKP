/**
 * @param {string} className
 * @returns {ClassDef}
 */
export function getClassDef(className) {
  const direct = CLASSES[className]
  if (direct) return direct
  const found = CLASS_ORDER.find((c) => c.toLowerCase() === String(className || '').toLowerCase())
  return found ? CLASSES[found] : CLASSES.Warrior
}

/**
 * @param {string} className
 * @returns {PrimaryRole}
 */
export function roleOf(className) {
  return getClassDef(className).role
}
